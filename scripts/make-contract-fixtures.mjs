// Build the contract fixtures from the REAL mod, inside the plugin repo.
//
// Copies the shipped window `geocentric_unga_main` out of
// `<mods>\geocentric_origin\interface\zz_geocentric_unga.gui` (read-only: the mod is never
// written to) into `scripts/fixtures/contract/`, together with the mod's own localisation keys and
// the hand-written button effect the window's close control names.
//
// Then it derives the FIVE BROKEN VARIANTS, each one a real defect from the project's history, as a
// minimal line-level rewrite of the same fixture so the diff IS the defect. Every rewrite is
// line-based on purpose: an earlier revision used string indices and produced a fixture whose only
// difference was whitespace, which would have tested nothing.
//
// Usage: node scripts/make-contract-fixtures.mjs

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, 'fixtures', 'contract');
const MOD = '<mods>\\geocentric_origin';
const SOURCE_GUI = join(MOD, 'interface', 'zz_geocentric_unga.gui');

mkdirSync(outDir, { recursive: true });

const source = readFileSync(SOURCE_GUI, 'utf8').replace(/^\uFEFF/, '');

/** The top-level `containerWindowType` block whose `name = "<window>"`, by brace counting. */
function extractWindow(text, windowName) {
  const lines = text.split('\n');
  let depth = 0;
  let start = null;
  for (const [index, line] of lines.entries()) {
    const opens = (line.match(/\{/g) ?? []).length;
    const closes = (line.match(/\}/g) ?? []).length;
    if (depth === 1 && /containerWindowType\s*=\s*\{/.test(line)) start = index;
    depth += opens - closes;
    if (start !== null && depth <= 1) {
      const block = lines.slice(start, index + 1).join('\n');
      if (new RegExp(`name\\s*=\\s*"${windowName}"`).test(block)) return { block, startLine: start + 1, endLine: index + 1 };
      start = null;
    }
  }
  return null;
}

/** The line index at which the element whose `name = "<name>"` line is `nameLine` closes. */
function elementEnd(lines, start) {
  let depth = 0;
  for (let index = start; index < lines.length; index += 1) {
    depth += (lines[index].match(/\{/g) ?? []).length - (lines[index].match(/\}/g) ?? []).length;
    if (depth === 0) return index;
  }
  throw new Error(`unterminated element starting at line ${start + 1}`);
}

/**
 * The first line index of an element whose `name` line is the next line.
 *
 * `indent` is the fixture's own convention, measured rather than assumed: the window's children are
 * at 3 tabs and the window itself at 2, because `guiTypes = {` wraps one tab and the window block
 * was lifted with its own indentation intact. `indent === null` searches at ANY depth, which is what
 * a rule that does not care where a name lives needs (a nested `portrait` icon, an `option_list`
 * inside EVENT_DIPLO).
 */
function findElement(lines, name, indent = null) {
  for (let index = 0; index < lines.length - 1; index += 1) {
    const current = lines[index];
    const tabs = current.length - current.replace(/^\t+/, '').length;
    if (indent !== null && tabs !== indent) continue;
    if (!/^[A-Za-z]+Type = \{$/.test(current.slice(tabs))) continue;
    if (lines[index + 1] === `${'\t'.repeat(tabs + 1)}name = "${name}"`) return index;
  }
  return -1;
}

const window = extractWindow(source, 'geocentric_unga_main');
if (!window) throw new Error('could not find geocentric_unga_main in the mod .gui');

// The file-level `@variables` the window uses, taken from the mod so no declaration is lost.
const variables = [...source.matchAll(/^(@[A-Za-z0-9_]+)\s*=\s*([^\s#]+)\s*$/gm)].map((match) => `${match[1]} = ${match[2]}`);

const legal = [
  '#------------------------------------------------------------------------------------',
  '# FIXTURE: a LEGAL custom_gui event window, lifted verbatim from the working mod',
  `# (\`geocentric_unga_main\`, <mods>\\geocentric_origin\\interface\\zz_geocentric_unga.gui`,
  `# lines ${window.startLine}-${window.endLine}).`,
  '#',
  '# Generated by scripts/make-contract-fixtures.mjs - do not hand-edit. It passes the custom_gui',
  '# contract check with ZERO findings: all 26 demanded names are declared, `option_list` is a direct',
  '# child of EVENT_DIPLO, the `portrait` icon is nested inside the `portrait` container, and `close`',
  '# is the window\'s last direct child.',
  '#------------------------------------------------------------------------------------',
  '',
  ...variables,
  '',
  'guiTypes = {',
  window.block
    .split('\n')
    .map((line) => `\t${line}`)
    .join('\n'),
  '}',
  '',
].join('\n');

writeFileSync(join(outDir, 'legal_window.gui'), legal, 'utf8');

