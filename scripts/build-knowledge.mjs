#!/usr/bin/env node
//------------------------------------------------------------------------------------
// build-knowledge.mjs -- Part of RStellarisGui
//
// Compiles the authored `knowledge/**/*.md` topics into the canonical artefacts:
//
//   1. resources/knowledge/stellaris/<category>/<id>.toml   portable, hand-readable topic
//                                                           files, one per knowledge topic.
//   2. src/generated/knowledge.mjs                          the snapshot the server embeds,
//                                                           so `node src/index.mjs` is a
//                                                           server WITH a knowledge base.
//
// Both are TRACKED, not ignored, and the reason is in `.gitignore`: this project has no build
// step, `npx rstellarisgui` / `node src/index.mjs` runs the sources directly, and `package.json`
// ships `src` and `resources`. An ignored `src/generated/knowledge.mjs` would make a fresh clone
// a server with no knowledge base until someone ran this script - and a clone that does not work
// is worse than a generated file in the repository. The sibling RStellarisScribe states the same
// reasoning in its own .gitignore, and this project stated it first; the two must agree.
//
// The build is DETERMINISTIC: the same sources produce byte-identical artefacts, so a rebuild is
// a no-op diff and a stale artefact is a test failure rather than a surprise.
//
//   node scripts/build-knowledge.mjs            rewrite both artefacts
//   node scripts/build-knowledge.mjs --check    report whether they are current (exit 1 if not)
//
// This program is free software: you can redistribute it and/or modify it under the terms of the
// GNU Affero General Public License as published by the Free Software Foundation, either version 3
// of the License, or (at your option) any later version.
//------------------------------------------------------------------------------------

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { KNOWLEDGE_CATEGORIES, readKnowledgeSources } from '../src/lib/knowledge-source.mjs';
import { topicToToml } from '../src/lib/knowledge.mjs';

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const knowledgeRoot = join(projectRoot, 'knowledge');
const canonicalRoot = join(projectRoot, 'resources', 'knowledge', 'stellaris');
const generatedDir = join(projectRoot, 'src', 'generated');
const generatedPath = join(generatedDir, 'knowledge.mjs');

/** The canonical relative path of a topic's TOML file: `<category>/<id>.toml`. */
export function canonicalTopicPath(topic) {
  const id = topic.id.split('.').join('/');
  return `${topic.category}/${id}.toml`;
}

/** The whole generated module, as text - a pure function of the topics and the update snapshot. */
export function buildGeneratedModule(topics, latestUpdate) {
  const sourcePaths = topics.map((topic) => canonicalTopicPath(topic));
  const snapshot = topics.map((topic, position) => ({ ...topic, source_path: sourcePaths[position] }));
  return [
    '// Generated by scripts/build-knowledge.mjs. Do not edit by hand.',
    '//',
    '// The compiled snapshot of knowledge/**.md, embedded so that `node src/index.mjs` serves a',
    '// knowledge base without a build step. Regenerate with: node scripts/build-knowledge.mjs',
    '',
    `export const categories = ${JSON.stringify(KNOWLEDGE_CATEGORIES, null, 2)};`,
    '',
    `export const topics = ${JSON.stringify(snapshot, null, 2)};`,
    '',
    `export const sourcePaths = ${JSON.stringify(sourcePaths, null, 2)};`,
    '',
    `export const latestUpdate = ${JSON.stringify(latestUpdate, null, 2)};`,
    '',
  ].join('\n');
}

/** Read the authored `knowledge/updates/latest-update.md` snapshot of the verified version. */
export function readLatestUpdate() {
  const fallback = {
    title: 'Stellaris 4.4.6 "Pegasus"',
    body: 'No bundled update snapshot is present in this checkout.',
  };
  const path = join(knowledgeRoot, 'updates', 'latest-update.md');
  if (!existsSync(path)) return fallback;
  const text = readFileSync(path, 'utf8').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');
  if (!text.startsWith('---')) return fallback;
  const end = text.indexOf('\n---', 3);
  if (end === -1) return fallback;
  const frontMatter = text.slice(text.indexOf('\n', 3) + 1, end);
  const titleLine = /^title:\s*(.*)$/m.exec(frontMatter);
  const afterMarker = text.indexOf('\n', end + 1);
  return {
    title: titleLine ? titleLine[1].trim().replace(/^["']|["']$/g, '') : fallback.title,
    body: afterMarker === -1 ? '' : text.slice(afterMarker + 1).trim(),
  };
}

/** Every canonical TOML file the build would write, as `path -> text`. */
export function buildArtifacts(topics) {
  const files = new Map();
  for (const topic of topics) {
    files.set(join(canonicalRoot, canonicalTopicPath(topic)), topicToToml(topic));
  }
  files.set(generatedPath, buildGeneratedModule(topics, readLatestUpdate()));
  return files;
}

/** Canonical TOML files currently on disk. */
function existingArtifacts() {
  const found = [];
  const walk = (directory) => {
    let entries;
    try {
      entries = readdirSync(directory, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      const full = join(directory, entry.name);
      if (entry.isDirectory()) walk(full);
      else found.push(full);
    }
  };
  walk(canonicalRoot);
  if (existsSync(generatedPath)) found.push(generatedPath);
  return found;
}

/**
 * Which artefacts differ from what the sources compile to.
 *
 * Returns `{stale: [...], orphaned: [...]}`: `stale` is a file whose text is wrong or missing,
 * `orphaned` is a canonical TOML file the sources no longer produce - which is a rename or a
 * deletion that was not carried through, and must not be left behind for a reader to trust.
 */
export function checkKnowledge() {
  const topics = readKnowledgeSources(knowledgeRoot);
  const wanted = buildArtifacts(topics);
  const stale = [];
  for (const [path, text] of wanted) {
    if (!existsSync(path)) stale.push({ path, reason: 'missing' });
    else if (readFileSync(path, 'utf8') !== text) stale.push({ path, reason: 'content differs' });
  }
  const orphaned = existingArtifacts().filter((path) => !wanted.has(path));
  return { stale, orphaned, topicCount: topics.length };
}

function main() {
  const check = process.argv.includes('--check');
  const topics = readKnowledgeSources(knowledgeRoot);

  if (check) {
    const { stale, orphaned } = checkKnowledge();
    if (stale.length === 0 && orphaned.length === 0) {
      process.stdout.write(`knowledge artefacts are current (${topics.length} topics).\n`);
      return;
    }
    for (const entry of stale) process.stdout.write(`STALE ${entry.path} (${entry.reason})\n`);
    for (const path of orphaned) process.stdout.write(`ORPHAN ${path} (no source produces it)\n`);
    process.stdout.write('run `node scripts/build-knowledge.mjs` to regenerate.\n');
    process.exitCode = 1;
    return;
  }

  // Clear the canonical tree first, so a renamed or deleted topic cannot leave a stale TOML file
  // behind that a reader - or a search - would still find.
  rmSync(canonicalRoot, { recursive: true, force: true });
  for (const [path, text] of buildArtifacts(topics)) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text, 'utf8');
  }

  const byCategory = new Map();
  for (const topic of topics) {
    byCategory.set(topic.category, (byCategory.get(topic.category) ?? 0) + 1);
  }
  const summary = [...byCategory.entries()]
    .sort()
    .map(([category, count]) => `${category}=${count}`)
    .join(' ');
  process.stdout.write(
    `built ${topics.length} knowledge topics (${summary})\n` +
      `  canonical: resources/knowledge/stellaris/\n` +
      `  snapshot:  src/generated/knowledge.mjs\n`,
  );
}

const invokedDirectly = process.argv[1] && import.meta.url.endsWith(process.argv[1].replace(/\\/g, '/').split('/').pop());
if (invokedDirectly) main();

export default { buildArtifacts, buildGeneratedModule, canonicalTopicPath, checkKnowledge, readLatestUpdate };
